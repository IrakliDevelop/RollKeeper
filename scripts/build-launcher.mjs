#!/usr/bin/env node
// Builds public/launcher.html, the static page served at `/` (see the
// rewrite in next.config.ts): the React launcher rendered once, the CSS it
// uses compiled from globals.css, the four fonts it uses, and two small
// inline scripts. No React or Next.js runtime ships to the browser.
//
//   npm run launcher:build   regenerate after changing the launcher
//   npm run launcher:check   fail if the committed page is out of date
import { build } from 'esbuild';
import { compile, optimize } from '@tailwindcss/node';
import { Scanner } from '@tailwindcss/oxide';
import {
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
  existsSync,
} from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const OUT_HTML = path.join(ROOT, 'public', 'launcher.html');
const FONT_DIR = path.join(ROOT, 'public', 'launcher-fonts');
const check = process.argv.includes('--check');

// The faces the launcher draws with, measured in the browser. Family names
// match next/font's, so fallbacks and weights resolve the same way.
const FONTS = [
  {
    family: 'vollkorn',
    file: 'vollkorn-latin-wght-normal.woff2',
    weight: '400 900',
  },
  { family: 'barlow', file: 'barlow-latin-400-normal.woff2', weight: '400' },
  { family: 'barlow', file: 'barlow-latin-500-normal.woff2', weight: '500' },
  {
    family: 'barlowCondensed',
    file: 'barlow-condensed-latin-600-normal.woff2',
    weight: '600',
  },
];

async function renderMarkup(work) {
  const outfile = path.join(work, 'render.cjs');
  await build({
    entryPoints: [path.join(ROOT, 'scripts', 'launcher', 'render.tsx')],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    jsx: 'automatic',
    packages: 'external',
    alias: { '@': SRC },
    logLevel: 'error',
  });
  const { renderLauncher } = createRequire(import.meta.url)(outfile);
  return renderLauncher();
}

async function buildCss(work, markup) {
  const scanFile = path.join(work, 'scan.html');
  writeFileSync(scanFile, markup);
  const input = readFileSync(path.join(SRC, 'app', 'globals.css'), 'utf8');
  // `source(none)`: only the rendered page is scanned, not the whole app.
  const compiler = await compile(
    input.replace(
      "@import 'tailwindcss';",
      "@import 'tailwindcss' source(none);"
    ),
    {
      base: path.join(SRC, 'app'),
      onDependency() {},
    }
  );
  const scanner = new Scanner({
    sources: [{ base: work, pattern: 'scan.html', negated: false }],
  });
  const css = compiler.build(scanner.scan());
  return optimize(css, { minify: true }).code;
}

function fontFaces() {
  return FONTS.map(
    f =>
      `@font-face{font-family:${f.family};src:url(/launcher-fonts/${f.file}) format("woff2");font-weight:${f.weight};font-style:normal;font-display:swap}`
  ).join('');
}

function page(
  { body, continueTemplate, themeScript, staticContinueScript },
  css
) {
  const preload = FONTS.map(
    f =>
      `<link rel="preload" href="/launcher-fonts/${f.file}" as="font" type="font/woff2" crossorigin>`
  ).join('');
  return `<!DOCTYPE html>
<!-- Generated by scripts/build-launcher.mjs from src/components/launcher. Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>RollKeeper</title>
<meta name="description" content="D&amp;D 5e character sheets for players, and initiative and battle maps for the DM.">
<link rel="icon" href="/rollkeeper_favicon.svg">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
${preload}
<script>${themeScript.trim()}</script>
<style>${fontFaces()}:root{--font-vollkorn:vollkorn;--font-barlow:barlow;--font-barlow-condensed:barlowCondensed}${css}</style>
</head>
<body class="antialiased">${body}${continueTemplate}<script>${staticContinueScript.trim()}</script></body>
</html>
`;
}

// Inside the repo, so the rendered bundle resolves packages from node_modules.
const CACHE = path.join(ROOT, 'node_modules', '.cache');
mkdirSync(CACHE, { recursive: true });
const work = mkdtempSync(path.join(CACHE, 'rk-launcher-'));
try {
  const parts = await renderMarkup(work);
  const css = await buildCss(work, parts.body + parts.continueTemplate);
  const html = page(parts, css);
  if (check) {
    const current = existsSync(OUT_HTML) ? readFileSync(OUT_HTML, 'utf8') : '';
    const fontsOk = FONTS.every(f => existsSync(path.join(FONT_DIR, f.file)));
    if (current !== html || !fontsOk) {
      console.error(
        'public/launcher.html is out of date. Run `npm run launcher:build`.'
      );
      process.exit(1);
    }
    console.log('Launcher page: OK');
  } else {
    mkdirSync(FONT_DIR, { recursive: true });
    for (const f of FONTS)
      copyFileSync(
        path.join(SRC, 'app', 'fonts', f.file),
        path.join(FONT_DIR, f.file)
      );
    writeFileSync(OUT_HTML, html);
    console.log(
      `Wrote public/launcher.html (${(html.length / 1024).toFixed(1)} KiB)`
    );
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
